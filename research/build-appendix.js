'use strict'

// Rebuilds the appendix of ROADMAP.md from research/appendix-decisions.json
// and the raw upstream dumps. Fails if any open issue or PR has no decision,
// if a decision names an item that is not a ROADMAP.md row, or if the counts
// don't match the dumps.
//
// Usage: node research/build-appendix.js

var fs = require('node:fs')
var path = require('node:path')
var assert = require('node:assert')

var root = path.join(__dirname, '..')
var roadmapPath = path.join(root, 'ROADMAP.md')
var raw = path.join(__dirname, 'raw')
var issues = JSON.parse(fs.readFileSync(path.join(raw, 'issues-open.json'), 'utf8'))
var prs = JSON.parse(fs.readFileSync(path.join(raw, 'prs-open.json'), 'utf8'))
var decisions = JSON.parse(fs.readFileSync(path.join(__dirname, 'appendix-decisions.json'), 'utf8'))

var HEADING = '## Appendix: every open upstream issue and pull request'
var roadmap = fs.readFileSync(roadmapPath, 'utf8')
var cut = roadmap.indexOf(HEADING)
assert.ok(cut !== -1, 'appendix heading not found in ROADMAP.md')
var body = roadmap.slice(0, cut)

// Every "Item" cell of a status table row (rows that start with a status box).
var titles = new Set()
body.split('\n').forEach(function (line) {
  var m = /^\| \[[ x~]\] \| (.+?) \| /.exec(line)
  if (m) titles.add(m[1])
})

var LABEL = {
  roadmap: 'Roadmap',
  'cherry-pick': 'Cherry-pick',
  'new-item': 'Roadmap',
  duplicate: 'Duplicate',
  'wont-do': "Won't do",
  support: 'Support question',
  'already-fixed': 'Already fixed',
  'upstream-process': 'Upstream process'
}

function cell (text) {
  return String(text == null ? '' : text).replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim()
}

function detail (d, number, kind) {
  switch (d.decision) {
    case 'roadmap':
    case 'cherry-pick':
    case 'new-item': {
      var item = d.item || d.proposed_item
      assert.ok(titles.has(item), kind + ' #' + number + ': no ROADMAP.md row titled "' + item + '"')
      return item
    }
    case 'duplicate':
      assert.ok(d.of, kind + ' #' + number + ': duplicate without "of"')
      return 'of #' + String(d.of).replace(/^#/, '')
    case 'wont-do':
      assert.ok(d.reason, kind + ' #' + number + ': won\'t do without a reason')
      return d.reason
    case 'already-fixed':
      return d.evidence || d.reason || ''
    default:
      return d.reason || ''
  }
}

function table (list, kind, map) {
  var expected = list.map(function (x) { return String(x.number) }).sort()
  assert.deepStrictEqual(Object.keys(map).sort(), expected, kind + ': decisions do not match the open list')
  var counts = {}
  var rows = list.slice().sort(function (a, b) { return a.number - b.number }).map(function (x) {
    var d = map[String(x.number)]
    assert.ok(LABEL[d.decision], kind + ' #' + x.number + ': unknown decision ' + d.decision)
    counts[LABEL[d.decision]] = (counts[LABEL[d.decision]] || 0) + 1
    var link = 'https://github.com/expressjs/express/' + (kind === 'PR' ? 'pull/' : 'issues/') + x.number
    return '| [#' + x.number + '](' + link + ') | ' + cell(x.title) + ' | ' + LABEL[d.decision] + ' | ' + cell(detail(d, x.number, kind)) + ' |'
  })
  return { rows: rows, counts: counts }
}

var it = table(issues, 'issue', decisions.issues)
var pt = table(prs, 'PR', decisions.prs)

function summary (counts) {
  return Object.keys(counts).sort().map(function (k) { return k + ' ' + counts[k] }).join(', ')
}

var out = [
  HEADING,
  '',
  'Generated by `node research/build-appendix.js` from `research/appendix-decisions.json` and the upstream snapshot in `research/raw/` (2026-11-21). Edit the JSON, not this section.',
  '',
  '"Roadmap" and "Cherry-pick" name the roadmap item that covers the entry. "Cherry-pick" means we take that PR\'s code.',
  '',
  '### Issues (' + issues.length + ')',
  '',
  summary(it.counts) + '.',
  '',
  '| Issue | Title | Decision | Item or reason |',
  '|---|---|---|---|'
].concat(it.rows, [
  '',
  '### Pull requests (' + prs.length + ')',
  '',
  summary(pt.counts) + '.',
  '',
  '| PR | Title | Decision | Item or reason |',
  '|---|---|---|---|'
], pt.rows, [''])

fs.writeFileSync(roadmapPath, body + out.join('\n'))
console.log('issues ' + issues.length + ' (' + summary(it.counts) + ')')
console.log('PRs ' + prs.length + ' (' + summary(pt.counts) + ')')
